-- DataPulse PostgreSQL schema. Run in a new project database.
-- The backend should use JPA/Hibernate for ordinary data access. This SQL file
-- defines the advanced database objects required by the assessment.

BEGIN;

CREATE TABLE roles (
    role_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name     varchar(30) NOT NULL UNIQUE,
    description   text,
    CONSTRAINT ck_roles_role_name CHECK (role_name IN ('ADMIN', 'ANALYST'))
);

CREATE TABLE users (
    user_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       bigint NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
    full_name     varchar(120) NOT NULL,
    email         varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_users_email_nonempty CHECK (length(trim(email)) > 0),
    CONSTRAINT ck_users_full_name_nonempty CHECK (length(trim(full_name)) > 0)
);
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

CREATE TABLE datasets (
    dataset_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     bigint NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    dataset_name varchar(160) NOT NULL,
    description  text,
    status       varchar(20) NOT NULL DEFAULT 'ACTIVE',
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_datasets_owner_name UNIQUE (owner_id, dataset_name),
    CONSTRAINT ck_datasets_status CHECK (status IN ('ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_datasets_name_nonempty CHECK (length(trim(dataset_name)) > 0)
);

CREATE TABLE dataset_fields (
    field_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id  bigint NOT NULL REFERENCES datasets(dataset_id) ON DELETE CASCADE,
    field_name  varchar(120) NOT NULL,
    data_type   varchar(20) NOT NULL DEFAULT 'TEXT',
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_dataset_fields_dataset_name UNIQUE (dataset_id, field_name),
    CONSTRAINT ck_dataset_fields_data_type
        CHECK (data_type IN ('TEXT', 'INTEGER', 'DECIMAL', 'DATE', 'BOOLEAN')),
    CONSTRAINT ck_dataset_fields_name_nonempty CHECK (length(trim(field_name)) > 0)
);

CREATE TABLE validation_rules (
    rule_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id    bigint NOT NULL REFERENCES dataset_fields(field_id) ON DELETE RESTRICT,
    rule_type   varchar(20) NOT NULL,
    severity    varchar(10) NOT NULL DEFAULT 'MEDIUM',
    rule_config jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_validation_rules_type
        CHECK (rule_type IN ('REQUIRED', 'UNIQUE', 'EMAIL', 'RANGE', 'TYPE')),
    CONSTRAINT ck_validation_rules_severity
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_validation_rules_config_object
        CHECK (jsonb_typeof(rule_config) = 'object')
);

CREATE TABLE validation_runs (
    run_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id      bigint NOT NULL REFERENCES datasets(dataset_id) ON DELETE RESTRICT,
    started_by      bigint NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    started_at      timestamptz NOT NULL DEFAULT now(),
    completed_at    timestamptz,
    status          varchar(20) NOT NULL DEFAULT 'QUEUED',
    total_rows      integer NOT NULL DEFAULT 0,
    issue_count     integer NOT NULL DEFAULT 0,
    failure_message text,
    CONSTRAINT ck_validation_runs_status
        CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_validation_runs_counts CHECK (total_rows >= 0 AND issue_count >= 0),
    CONSTRAINT ck_validation_runs_completed_time
        CHECK (status <> 'COMPLETED' OR completed_at IS NOT NULL)
);

CREATE TABLE quality_issues (
    issue_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         bigint NOT NULL REFERENCES validation_runs(run_id) ON DELETE RESTRICT,
    rule_id        bigint NOT NULL REFERENCES validation_rules(rule_id) ON DELETE RESTRICT,
    row_number     integer NOT NULL,
    severity       varchar(10) NOT NULL,
    message        text NOT NULL,
    observed_value text,
    status         varchar(20) NOT NULL DEFAULT 'OPEN',
    created_at     timestamptz NOT NULL DEFAULT now(),
    resolved_at    timestamptz,
    CONSTRAINT uq_quality_issues_run_rule_row UNIQUE (run_id, rule_id, row_number),
    CONSTRAINT ck_quality_issues_row_number CHECK (row_number > 0),
    CONSTRAINT ck_quality_issues_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_quality_issues_status CHECK (status IN ('OPEN', 'RESOLVED', 'WAIVED')),
    CONSTRAINT ck_quality_issues_resolution_time
        CHECK ((status = 'OPEN' AND resolved_at IS NULL) OR
               (status <> 'OPEN' AND resolved_at IS NOT NULL))
);

CREATE TABLE issue_resolutions (
    resolution_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id           bigint NOT NULL REFERENCES quality_issues(issue_id) ON DELETE RESTRICT,
    resolved_by_user_id bigint NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    action             varchar(20) NOT NULL,
    note               text NOT NULL,
    resolved_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_issue_resolutions_action
        CHECK (action IN ('FIXED', 'WAIVED', 'REOPENED')),
    CONSTRAINT ck_issue_resolutions_note_nonempty CHECK (length(trim(note)) > 0)
);

CREATE TABLE quality_scores (
    score_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              bigint NOT NULL UNIQUE REFERENCES validation_runs(run_id) ON DELETE RESTRICT,
    completeness_score  numeric(5,2) NOT NULL,
    validity_score      numeric(5,2) NOT NULL,
    uniqueness_score    numeric(5,2) NOT NULL,
    overall_score       numeric(5,2) NOT NULL,
    calculated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_quality_scores_range CHECK (
        completeness_score BETWEEN 0 AND 100 AND
        validity_score BETWEEN 0 AND 100 AND
        uniqueness_score BETWEEN 0 AND 100 AND
        overall_score BETWEEN 0 AND 100
    )
);

CREATE TABLE audit_logs (
    log_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id bigint REFERENCES users(user_id) ON DELETE SET NULL,
    entity_type   varchar(40) NOT NULL,
    entity_id     bigint NOT NULL,
    action        varchar(40) NOT NULL,
    old_values    jsonb,
    new_values    jsonb,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- Indexes support the app's common filters, joins, and history pages.
CREATE INDEX ix_datasets_owner_status ON datasets(owner_id, status);
CREATE INDEX ix_dataset_fields_dataset ON dataset_fields(dataset_id);
CREATE INDEX ix_validation_rules_field_active ON validation_rules(field_id, is_active);
CREATE INDEX ix_validation_runs_dataset_started ON validation_runs(dataset_id, started_at DESC);
CREATE INDEX ix_quality_issues_run_status_severity ON quality_issues(run_id, status, severity);
CREATE INDEX ix_issue_resolutions_issue_time ON issue_resolutions(issue_id, resolved_at DESC);
CREATE INDEX ix_audit_logs_entity_time ON audit_logs(entity_type, entity_id, created_at DESC);

-- Summary view used by the dashboard: one latest completed score and current
-- open-issue count per dataset.
CREATE VIEW dataset_quality_summary AS
SELECT
    d.dataset_id,
    d.dataset_name,
    d.status AS dataset_status,
    latest.run_id AS latest_run_id,
    latest.overall_score AS latest_overall_score,
    COALESCE(open_issues.open_issue_count, 0)::bigint AS open_issue_count
FROM datasets AS d
LEFT JOIN LATERAL (
    SELECT vr.run_id, qs.overall_score
    FROM validation_runs AS vr
    JOIN quality_scores AS qs ON qs.run_id = vr.run_id
    WHERE vr.dataset_id = d.dataset_id AND vr.status = 'COMPLETED'
    ORDER BY vr.completed_at DESC, vr.run_id DESC
    LIMIT 1
) AS latest ON true
LEFT JOIN LATERAL (
    SELECT count(*) AS open_issue_count
    FROM quality_issues AS qi
    JOIN validation_runs AS vr ON vr.run_id = qi.run_id
    WHERE vr.dataset_id = d.dataset_id AND qi.status = 'OPEN'
) AS open_issues ON true;

-- Score procedure. The application must call this inside the same transaction
-- that finalizes the run and writes its issues.
CREATE PROCEDURE recalculate_quality_score(IN p_run_id bigint)
LANGUAGE plpgsql
AS $$
DECLARE
    v_dataset_id       bigint;
    v_total_rows       bigint;
    v_field_count      bigint;
    v_total_cells      bigint;
    v_missing_cells    bigint;
    v_duplicate_cells  bigint;
    v_invalid_cells    bigint;
    v_completeness     numeric(5,2);
    v_validity         numeric(5,2);
    v_uniqueness       numeric(5,2);
    v_overall          numeric(5,2);
BEGIN
    SELECT dataset_id, total_rows
      INTO v_dataset_id, v_total_rows
      FROM validation_runs
     WHERE run_id = p_run_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Validation run % does not exist', p_run_id;
    END IF;

    SELECT count(*) INTO v_field_count
      FROM dataset_fields
     WHERE dataset_id = v_dataset_id AND is_active = true;

    v_total_cells := v_total_rows * v_field_count;

    SELECT count(DISTINCT (qi.row_number, vr.field_id))
      INTO v_missing_cells
      FROM quality_issues AS qi
      JOIN validation_rules AS vr ON vr.rule_id = qi.rule_id
     WHERE qi.run_id = p_run_id AND vr.rule_type = 'REQUIRED';

    SELECT count(DISTINCT (qi.row_number, vr.field_id))
      INTO v_duplicate_cells
      FROM quality_issues AS qi
      JOIN validation_rules AS vr ON vr.rule_id = qi.rule_id
     WHERE qi.run_id = p_run_id AND vr.rule_type = 'UNIQUE';

    SELECT count(DISTINCT (qi.row_number, vr.field_id))
      INTO v_invalid_cells
      FROM quality_issues AS qi
      JOIN validation_rules AS vr ON vr.rule_id = qi.rule_id
     WHERE qi.run_id = p_run_id;

    IF v_total_cells = 0 THEN
        v_completeness := 0;
        v_validity := 0;
        v_uniqueness := 0;
    ELSE
        v_completeness := round(100.0 * (v_total_cells - LEAST(v_missing_cells, v_total_cells)) / v_total_cells, 2);
        v_validity := round(100.0 * (v_total_cells - LEAST(v_invalid_cells, v_total_cells)) / v_total_cells, 2);
        v_uniqueness := round(100.0 * (v_total_cells - LEAST(v_duplicate_cells, v_total_cells)) / v_total_cells, 2);
    END IF;

    v_overall := round((v_completeness + v_validity + v_uniqueness) / 3.0, 2);

    INSERT INTO quality_scores (
        run_id, completeness_score, validity_score, uniqueness_score, overall_score, calculated_at
    ) VALUES (
        p_run_id, v_completeness, v_validity, v_uniqueness, v_overall, now()
    )
    ON CONFLICT (run_id) DO UPDATE SET
        completeness_score = EXCLUDED.completeness_score,
        validity_score = EXCLUDED.validity_score,
        uniqueness_score = EXCLUDED.uniqueness_score,
        overall_score = EXCLUDED.overall_score,
        calculated_at = EXCLUDED.calculated_at;
END;
$$;

-- Audit issue creation and status transitions. The backend may set a transaction
-- local value with: SET LOCAL app.user_id = '<authenticated user ID>'.
CREATE FUNCTION audit_quality_issue_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_actor_user_id bigint;
BEGIN
    v_actor_user_id := NULLIF(current_setting('app.user_id', true), '')::bigint;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO audit_logs (
            actor_user_id, entity_type, entity_id, action, old_values, new_values
        ) VALUES (
            v_actor_user_id, 'QUALITY_ISSUE', NEW.issue_id, 'ISSUE_CREATED', NULL,
            jsonb_build_object('status', NEW.status, 'run_id', NEW.run_id, 'rule_id', NEW.rule_id)
        );
    ELSIF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO audit_logs (
            actor_user_id, entity_type, entity_id, action, old_values, new_values
        ) VALUES (
            v_actor_user_id, 'QUALITY_ISSUE', NEW.issue_id, 'ISSUE_STATUS_CHANGED',
            jsonb_build_object('status', OLD.status), jsonb_build_object('status', NEW.status)
        );
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_audit_quality_issue_change
AFTER INSERT OR UPDATE ON quality_issues
FOR EACH ROW
EXECUTE FUNCTION audit_quality_issue_change();

